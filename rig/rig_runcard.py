"""rig_runcard.py -- print the exact rig-day commands for one phase with every
hand-substituted field filled in, and write them to day_<day>/runcard_<phase>.txt.

    python rig/rig_runcard.py --phase gate --day 2026-10-08 [--depth 1]
    python rig/rig_runcard.py --phase dutyid --day 2026-10-08 --resp 1,3,4,6
    python rig/rig_runcard.py --phase fit --day 2026-10-08 --ctrl 34,40
    python rig/rig_runcard.py --phase arm --day 2026-10-08 --arm mpc --run 1 \
        --resp 1,3,4,6 --ctrl 34,40 --baseline 2.1e-4
    python rig/rig_runcard.py --phase rsweep --day 2026-10-08 --resp 1,3,4,6 --ctrl 34,40

Phases: phase0 gate quiet thwack burst gap dutyid fit refs arm rsweep drift
(--phase all prints every phase in order with placeholders where a value is
still unknown).

What it removes from the runbook (RIG_DAY_2026-10-08.md): the hand-typed
-Ticks per design (now -Design), the inline pandas one-liner that wrote
design_rundutyid.csv with no meta/validation (now written here with its meta
and validated: must print DESIGN OK), the 8 hand-filled fields of
build_interleaved_run, the per-arm --pairs/--feature-map retyping, and the
"watch the banner" steps (now run_audit.py). Every command below is emitted
with the current flag set (-Design/-Capture/-Baseline, run_audit, r-schedule).
"""

