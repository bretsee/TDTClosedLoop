def design_ticks(csv_path):
    meta = os.path.splitext(csv_path)[0] + "_meta.json"
    if os.path.isfile(meta):
        with open(meta) as f:
            return int(json.load(f).get("nTicks", 0))
    if os.path.isfile(csv_path):
        with open(csv_path) as f:
            return sum(1 for _ in f) - 1
    return 0


def ph(name):
    return "\n# ---------------- %s ----------------" % name


